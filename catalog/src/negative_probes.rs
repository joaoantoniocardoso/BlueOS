pub fn negative_probe_url(base: &str, probe: &NegativeProbe) -> String {
    let url = crate::runner::join_url(base, probe.path);
    match probe.query {
        Some(query) => format!("{url}?{query}"),
        None => url,
    }
}

pub fn format_negative_dry_run(probe: &NegativeProbe, url: &str) -> String {
    format!(
        "DRY-RUN {} {} {} → {url}",
        probe.id,
        crate::runner::http_method_label(&probe.method),
        probe.path
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn negative_probe_ids_are_unique() {
        let mut seen = HashSet::new();
        for probe in NEGATIVE_PROBES {
            assert!(seen.insert(probe.id), "duplicate probe id {}", probe.id);
        }
    }

    #[test]
    fn every_negative_probe_path_starts_with_slash() {
        for probe in NEGATIVE_PROBES {
            assert!(
                probe.path.starts_with('/'),
                "{} path must start with /: {}",
                probe.id,
                probe.path
            );
        }
    }

    #[test]
    fn np04_query_contains_far_past_timestamp() {
        let np04 = NEGATIVE_PROBES
            .iter()
            .find(|probe| probe.id == "NP-04")
            .expect("NP-04");
        let query = np04.query.expect("NP-04 query");
        assert!(
            query.contains("1700000000"),
            "NP-04 must use unix_time_seconds=1700000000: {query}"
        );
    }
}
